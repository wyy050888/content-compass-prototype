const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'C:/Users/嗡嗡/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true,args:['--no-sandbox','--allow-file-access-from-files']});
  const page = await browser.newPage({viewport:{width:1600,height:1000}});
  const errors=[]; page.on('pageerror', e=>errors.push(e.stack));
  await page.goto('file:///'+path.resolve(__dirname,'../index.html').replaceAll('\\','/'));
  await page.waitForTimeout(1200);
  console.log('INIT',await page.evaluate(()=>({app:!!window.ProductCardApp,worker:!!window.ProductCardApp?.distribution?.startExecution,permissions:!!window.ContentCompassPermissions,scripts:document.querySelectorAll('script[src]').length})));
  console.log('PAGE_ERRORS',errors.length);
  await page.locator('[data-pc-nav="generation"]').click();
  await page.waitForTimeout(300);
  assert.match(await page.locator('#pcGenerationMetrics').innerText(),/今日生图处理数/);
  assert.equal(await page.locator('#pcGenerationScope .active').getAttribute('data-scope'),'all');
  assert(await page.evaluate(()=>ProductCardApp.data.images.every(x=>!!x.generatedAt)));
  await page.evaluate(() => {
    const task = ProductCardApp.data.generationTasks.find(item => ProductCardApp.data.images.some(image => image.taskId === item.id));
    ProductCardApp.openGenerationScreening(task);
  });
  const screeningPreview = await page.locator('.pc-screen-open').first().boundingBox();
  assert(screeningPreview && Math.abs(screeningPreview.width - screeningPreview.height) < 1, `screening preview is not 1:1: ${JSON.stringify(screeningPreview)}`);
  assert.doesNotMatch(await page.locator('.pc-screen-card .pc-image-meta').first().innerText(), /规则\s*\d+/);
  await page.locator('.pc-screen-open').first().click();
  assert.doesNotMatch(await page.locator('#pcScreenViewerIndex').innerText(), /规则\s*\d+/);
  const viewerInfoBoxes = await page.locator('.pc-screen-viewer-info>div').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect()).map(box => ({ right:box.right })));
  assert(Math.abs(viewerInfoBoxes[2].right - viewerInfoBoxes[3].right) < 1, `prompt and generation time are not right aligned: ${JSON.stringify(viewerInfoBoxes)}`);
  await page.locator('.pc-screen-viewer [data-screen-viewer-close]').click();
  await page.getByRole('dialog', { name:'筛选生成图片' }).getByLabel('关闭').click();
  await page.locator('[data-pc-nav="distribution"]').click();
  assert.doesNotMatch(await page.locator('#pcDistributionToolbar').innerText(), /结果确认中|异常中断/);
  assert.equal(await page.evaluate(() => ProductCardApp.distribution.taskStatusText('confirming')), '分发中');
  assert.equal(await page.evaluate(() => ProductCardApp.distribution.taskStatusText('interrupted')), '分发失败');
  await page.locator('#pcPrimaryAction').click();
  await page.locator('[data-wizard-task]').first().check();
  const wizardCardText = await page.locator('.pc-wizard-image-meta').first().innerText();
  const selectedSourceTaskName = await page.locator('[data-wizard-task]:checked').first().evaluate(node => ProductCardApp.data.generationTasks.find(item => item.id === node.dataset.wizardTask)?.name || '');
  assert(!selectedSourceTaskName || !wizardCardText.includes(selectedSourceTaskName), `source task name is still visible outside details: ${wizardCardText}`);
  const wizardMetaLayout = await page.locator('.pc-wizard-image-meta').first().evaluate(node => {
    const name = node.querySelector('strong').getBoundingClientRect();
    const time = node.querySelector('.pc-image-time').getBoundingClientRect();
    return { nameTop:name.top, timeTop:time.top };
  });
  assert(wizardMetaLayout.timeTop > wizardMetaLayout.nameTop, `generation time is not at card bottom: ${JSON.stringify(wizardMetaLayout)}`);
  await page.locator('[data-image-bulk="all"]').click();
  await page.locator('[data-wizard-action="next"]').click();
  await page.locator('[data-wizard-shop]').first().check();
  await page.locator('[data-plan-bulk="all"]').click();
  const values=await page.locator('[data-wizard-qty]').evaluateAll(nodes=>nodes.map(n=>n.value));
  console.log('ALLOCATED',values);
  await page.locator('[data-wizard-action="next"]').click();
  const footerAlignment = await page.locator('.pc-drawer-foot').evaluate(node => {
    const footer = node.getBoundingClientRect();
    const previous = node.querySelector('[data-wizard-action="prev"]').getBoundingClientRect();
    const submit = node.querySelector('[data-wizard-action="submit"]').getBoundingClientRect();
    return { footerLeft:footer.left, footerRight:footer.right, previousLeft:previous.left, submitRight:submit.right };
  });
  assert(footerAlignment.previousLeft - footerAlignment.footerLeft < 30, `previous button is not left aligned: ${JSON.stringify(footerAlignment)}`);
  assert(footerAlignment.footerRight - footerAlignment.submitRight < 30, `submit button is not right aligned: ${JSON.stringify(footerAlignment)}`);
  await page.locator('[data-toggle-plan-images]').first().click();
  const resultCardText = await page.locator('.pc-distribution-image-meta').first().innerText();
  assert(!selectedSourceTaskName || !resultCardText.includes(selectedSourceTaskName), `result card still exposes source task name: ${resultCardText}`);
  const resultMetaLayout = await page.locator('.pc-distribution-image-meta').first().evaluate(node => {
    const name = node.querySelector('strong').getBoundingClientRect();
    const time = node.querySelector('.pc-image-time').getBoundingClientRect();
    return { nameTop:name.top, timeTop:time.top };
  });
  assert(resultMetaLayout.timeTop > resultMetaLayout.nameTop, `result generation time is not at card bottom: ${JSON.stringify(resultMetaLayout)}`);
  await page.locator('[data-open-distribution-image]').first().click();
  assert(await page.locator('#pcDistributionViewerBody').innerText());
  await page.locator('.pc-distribution-viewer [data-distribution-viewer-close]').click();
  await page.locator('[data-wizard-action="submit"]').click();
  await page.locator('[data-pc-confirm="ok"]').click();
  await page.waitForTimeout(1100);
  const task=await page.evaluate(()=>{const t=ProductCardApp.data.distributionTasks[0];return {id:t.id,status:t.status,success:t.success,requested:t.requested};});
  console.log('SUBMITTED',task);
  assert(task.success>0 && task.success<task.requested);
  assert.equal(task.status,'uploading');
  assert.equal(errors.length,0,errors.join('\n'));
  await browser.close();
  console.log('PASS smoke');
})().catch(e=>{console.error(e);process.exit(1)});
